/// Closed metadata only. No original business IDs, payment material or messages.
class DiagnosticCommerceDetails {
  DiagnosticCommerceDetails({
    required this.stage,
    this.reason,
    String productRef = '',
    String skuRef = '',
    String quoteRef = '',
    String orderRef = '',
    String transactionRef = '',
    String requestRef = '',
    String state = '',
    String paymentState = '',
    String fulfillmentState = '',
    String currency = '',
    String price = '',
    String nativeDomain = '',
    String nativeStage = '',
    String businessCode = '',
    this.requested,
    this.found,
    this.available,
    this.amountFen,
    this.nativeCode,
  }) : businessCode = _businessCodes.contains(businessCode) ? businessCode : '',
       productRef = _ref(productRef),
       skuRef = _ref(skuRef),
       quoteRef = _ref(quoteRef),
       orderRef = _ref(orderRef),
       transactionRef = _ref(transactionRef),
       requestRef = _ref(requestRef),
       state = _states.contains(state) ? state : '',
       paymentState =
           const {
             'PENDING',
             'PROCESSING',
             'SUCCEEDED',
             'FAILED',
             'CANCELED',
             'CLOSED',
           }.contains(paymentState)
           ? paymentState
           : '',
       fulfillmentState =
           const {
             'NOT_STARTED',
             'PROCESSING',
             'SUCCEEDED',
             'EXCEPTION',
           }.contains(fulfillmentState)
           ? fulfillmentState
           : '',
       currency = RegExp(r'^[A-Z]{3}$').hasMatch(currency) ? currency : '',
       price = RegExp(r'^\d{1,15}(?:\.\d{1,20})?$').hasMatch(price)
           ? price
           : '',
       nativeStage =
           const {
             'validation',
             'products',
             'purchase',
             'purchaseGate',
             'productUnavailable',
             'verification',
             'verificationUnverified',
             'verificationProductMismatch',
             'verificationTokenMissing',
             'verificationTokenMismatch',
             'verificationTypeUnsupported',
             'finishLookup',
             'productsArguments',
           }.contains(nativeStage)
           ? nativeStage
           : '',
       nativeDomain =
           const {
             'SKErrorDomain',
             'StoreKit.StoreKitError',
             'NSURLErrorDomain',
             'SKInternalErrorDomain',
           }.contains(nativeDomain)
           ? nativeDomain
           : '';
  static const _businessCodes = {
    'COMMERCE_ORDER_MINUTE_LIMITED',
    'COMMERCE_ORDER_HOUR_LIMITED',
    'COMMERCE_MATERIAL_INTERVAL_LIMITED',
    'COMMERCE_MATERIAL_LIMIT_REACHED',
    'COMMERCE_SERVICE_UNAVAILABLE',
    'COMMERCE_NETWORK_UNAVAILABLE',
    'AC0006',
    'PAYMENT_VERIFICATION_FAILED',
    'ACCOUNT_MISMATCH',
    'CHANNEL_UNAVAILABLE',
    'MEMBERSHIP_ORDER_EXISTS',
    'MEMBERSHIP_PAYMENT_UNKNOWN',
    'MEMBERSHIP_STATE_CONFLICT',
    'MEMBERSHIP_SYNCING',
    'MEMBERSHIP_REVIEW_REQUIRED',
    'LEGACY_MEMBERSHIP_REVIEW_REQUIRED',
    'RECOVERY_CONFIRMATION_REQUIRED',
    'RECOVERY_PREVIEW_EXPIRED',
    'RECOVERY_PRICING_UNAVAILABLE',
    'APPLE_PRICE_CHANGED',
    'APPLE_ATTEMPT_STORAGE_UNAVAILABLE',
    'APPLE_RECOVERY_TIMEOUT',
    'PRODUCT_UNAVAILABLE',
  };
  final String businessCode;
  final CommerceStage stage;
  final CommerceReason? reason;
  final String productRef,
      skuRef,
      quoteRef,
      orderRef,
      transactionRef,
      requestRef,
      state,
      currency,
      price,
      nativeDomain,
      nativeStage,
      paymentState,
      fulfillmentState;
  final int? requested, found, amountFen, nativeCode;
  final bool? available;
  static const _states = {
    'waiting',
    'transaction',
    'started',
    'resolved',
    'submitted',
    'failed',
    'exhausted',
    'PENDING',
    'PROCESSING',
    'SUCCEEDED',
    'FAILED',
    'CANCELED',
    'CLOSED',
    'NOT_STARTED',
    'EXCEPTION',
    'consumable',
    'nonRenewable',
    'cancelled',
    'canceled',
    'pendingPayment',
    'paying',
    'paymentFailed',
    'closed',
    'pending',
    'unknown',
    'material',
    'accepted',
    'declined',
    'completed',
    'crediting',
    'unavailable',
  };
  static String _ref(String value) =>
      RegExp(r'^[a-f0-9]{16}$').hasMatch(value) ? value : '';
  Map<String, Object> toJson() => {
    'stage': stage.name,
    if (businessCode.isNotEmpty) 'businessCode': businessCode,
    if (reason != null) 'reason': reason!.name,
    if (productRef.isNotEmpty) 'productRef': productRef,
    if (skuRef.isNotEmpty) 'skuRef': skuRef,
    if (quoteRef.isNotEmpty) 'quoteRef': quoteRef,
    if (orderRef.isNotEmpty) 'orderRef': orderRef,
    if (transactionRef.isNotEmpty) 'transactionRef': transactionRef,
    if (requestRef.isNotEmpty) 'requestRef': requestRef,
    if (state.isNotEmpty) 'state': state,
    if (paymentState.isNotEmpty) 'paymentState': paymentState,
    if (fulfillmentState.isNotEmpty) 'fulfillmentState': fulfillmentState,
    if (currency.isNotEmpty) 'currency': currency,
    if (price.isNotEmpty) 'price': price,
    if (nativeDomain.isNotEmpty) 'nativeDomain': nativeDomain,
    if (nativeStage.isNotEmpty) 'nativeStage': nativeStage,
    if (nativeCode != null) 'nativeCode': nativeCode!.clamp(-999999, 999999),
    if (requested != null) 'requested': requested!.clamp(0, 10000),
    if (found != null) 'found': found!.clamp(0, 10000),
    if (amountFen != null) 'amountFen': amountFen!.clamp(0, 1000000000000),
    if (available != null) 'available': available!,
  };
  factory DiagnosticCommerceDetails.fromJson(Map<String, dynamic> json) =>
      DiagnosticCommerceDetails(
        stage: CommerceStage.values.firstWhere(
          (v) => v.name == json['stage'],
          orElse: () => CommerceStage.unknown,
        ),
        reason: json['reason'] == null
            ? null
            : CommerceReason.values.firstWhere(
                (v) => v.name == json['reason'],
                orElse: () => CommerceReason.unknown,
              ),
        productRef: json['productRef'] as String? ?? '',
        skuRef: json['skuRef'] as String? ?? '',
        quoteRef: json['quoteRef'] as String? ?? '',
        orderRef: json['orderRef'] as String? ?? '',
        transactionRef: json['transactionRef'] as String? ?? '',
        requestRef: json['requestRef'] as String? ?? '',
        state: json['state'] as String? ?? '',
        paymentState: json['paymentState'] as String? ?? '',
        fulfillmentState: json['fulfillmentState'] as String? ?? '',
        currency: json['currency'] as String? ?? '',
        price: json['price'] as String? ?? '',
        nativeDomain: json['nativeDomain'] as String? ?? '',
        nativeStage: json['nativeStage'] as String? ?? '',
        businessCode: json['businessCode'] as String? ?? '',
        nativeCode: json['nativeCode'] as int?,
        requested: json['requested'] as int?,
        found: json['found'] as int?,
        amountFen: json['amountFen'] as int?,
        available: json['available'] as bool?,
      );
}
